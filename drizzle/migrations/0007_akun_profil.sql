-- lulustes: akun peserta sederhana, profil, dan paket harian 25 soal (needs 0006).
--   * Akun: a guest can claim a username and password (bcrypt, pgcrypto) so
--     the same participant can sign in from another browser. Signing in hands
--     that browser its own key, kept in guest_keys; guest_key_ok accepts it,
--     so every existing participant function works for signed-in browsers.
--     Claiming keeps the guest's history and streak; signing in on a browser
--     that was a plain guest moves that guest's attempts into the account.
--     An account stays optional.
--   * Profil: get_profile returns the streak (from get_daily), totals, every
--     package day with the first attempt's score, and the latest attempts.
--   * Paket harian berisi 25 soal mulai 14 November 2026; #2 is seeded here.
-- Idempotent.

-- ============ ACCOUNTS ============
alter table public.guests add column if not exists username text;
alter table public.guests add column if not exists password_hash text;
create unique index if not exists guests_username_key on public.guests (username);
alter table public.guests drop constraint if exists guests_username_check;
alter table public.guests
  add constraint guests_username_check check (username is null or username ~ '^[a-z0-9_.]{3,20}$');

-- One row per signed-in browser; only the key's hash is stored.
create table if not exists public.guest_keys (
  key_hash text primary key,
  guest_id uuid not null references public.guests(id) on delete cascade,
  created_at timestamptz not null default now()
);
alter table public.guest_keys enable row level security;
grant all on public.guest_keys to service_role;
-- No grants or policies for anon/authenticated: only the functions below read it.
create index if not exists guest_keys_guest_idx on public.guest_keys (guest_id);

-- The key a guest was created with, or the key of a browser that signed in.
create or replace function public.guest_key_ok(p_guest_id uuid, p_guest_key text)
returns boolean
language sql stable security definer set search_path = public
as $$
  with h as (select encode(sha256(convert_to(coalesce(p_guest_key, ''), 'UTF8')), 'hex') as v)
  select exists (select 1 from guests g, h where g.id = p_guest_id and g.key_hash = h.v)
      or exists (select 1 from guest_keys k, h where k.guest_id = p_guest_id and k.key_hash = h.v);
$$;
revoke all on function public.guest_key_ok(uuid, text) from public, anon, authenticated;

-- "@Budi.S " -> "budi.s"
create or replace function public.clean_username(p_username text)
returns text
language sql immutable
as $$ select lower(regexp_replace(btrim(coalesce(p_username, '')), '^@', '')) $$;

-- Create an account. When this browser's guest checks out and has no account
-- yet, that guest becomes the account (history and streak kept); otherwise a
-- new guest is created under p_guest_key.
create or replace function public.register_account(
  p_username text, p_password text, p_nama text,
  p_guest_key text, p_guest_id uuid default null
)
returns table (guest_id uuid, nama text, username text)
language plpgsql security definer set search_path = public
as $$
#variable_conflict use_column
declare
  v_user text := public.clean_username(p_username);
  v_nama text := left(regexp_replace(btrim(coalesce(p_nama, '')), '\s+', ' ', 'g'), 40);
  v_hash text;
  v_guest uuid;
begin
  if v_user !~ '^[a-z0-9_.]{3,20}$' then
    raise exception 'Nama pengguna 3–20 karakter: huruf kecil, angka, titik, atau garis bawah.'
      using errcode = '22023';
  end if;
  if char_length(coalesce(p_password, '')) < 6 then
    raise exception 'Kata sandi minimal 6 karakter.' using errcode = '22023';
  end if;
  if char_length(v_nama) < 2 then
    raise exception 'Tulis namamu dulu, minimal 2 huruf.' using errcode = '22023';
  end if;
  if coalesce(char_length(p_guest_key), 0) < 16 then
    raise exception 'Kunci peserta tidak valid.' using errcode = '22023';
  end if;

  v_hash := extensions.crypt(p_password, extensions.gen_salt('bf', 8));
  begin
    if p_guest_id is not null
      and public.guest_key_ok(p_guest_id, p_guest_key)
      and exists (select 1 from guests g where g.id = p_guest_id and g.username is null)
    then
      v_guest := p_guest_id;
      update guests g set username = v_user, password_hash = v_hash, nama = v_nama
      where g.id = v_guest;
    else
      insert into guests (nama, key_hash, username, password_hash)
      values (v_nama, encode(sha256(convert_to(p_guest_key, 'UTF8')), 'hex'), v_user, v_hash)
      returning guests.id into v_guest;
    end if;
  exception when unique_violation then
    raise exception 'Nama pengguna itu sudah dipakai. Coba yang lain.' using errcode = '23505';
  end;

  return query select v_guest, v_nama, v_user;
end
$$;

-- Sign in from any browser: checks the password and registers p_new_key
-- (generated by the browser) as one more key of that guest. When the
-- browser was a plain guest (no account) whose key checks out, that guest's
-- attempts move into the account, so signing in right after a test keeps
-- the score; the emptied guest is removed.
drop function if exists public.login_account(text, text, text);
create or replace function public.login_account(
  p_username text, p_password text, p_new_key text,
  p_guest_id uuid default null, p_guest_key text default null
)
returns table (guest_id uuid, nama text, username text)
language plpgsql security definer set search_path = public
as $$
#variable_conflict use_column
declare
  v_g public.guests%rowtype;
begin
  if coalesce(char_length(p_new_key), 0) < 16 then
    raise exception 'Kunci peserta tidak valid.' using errcode = '22023';
  end if;
  select * into v_g from guests g where g.username = public.clean_username(p_username);
  if not found or v_g.password_hash is null then
    -- Same work as a real check, so a wrong username is not faster to spot.
    perform extensions.crypt(coalesce(p_password, ''), extensions.gen_salt('bf', 8));
    raise exception 'Nama pengguna atau kata sandi salah.' using errcode = '28P01';
  end if;
  if v_g.password_hash <> extensions.crypt(coalesce(p_password, ''), v_g.password_hash) then
    raise exception 'Nama pengguna atau kata sandi salah.' using errcode = '28P01';
  end if;

  insert into guest_keys (key_hash, guest_id)
  values (encode(sha256(convert_to(p_new_key, 'UTF8')), 'hex'), v_g.id)
  on conflict (key_hash) do nothing;

  if p_guest_id is not null and p_guest_id <> v_g.id
    and public.guest_key_ok(p_guest_id, p_guest_key)
    and exists (select 1 from guests g where g.id = p_guest_id and g.username is null)
  then
    update attempts a set guest_id = v_g.id where a.guest_id = p_guest_id;
    delete from guests g where g.id = p_guest_id;
  end if;

  return query select v_g.id, v_g.nama, v_g.username;
end
$$;

-- Sign this browser out: its sign-in key stops working.
create or replace function public.logout_account(p_guest_id uuid, p_guest_key text)
returns void
language sql security definer set search_path = public
as $$
  delete from guest_keys k
  where k.guest_id = p_guest_id
    and k.key_hash = encode(sha256(convert_to(coalesce(p_guest_key, ''), 'UTF8')), 'hex');
$$;

-- ============ PROFILE ============
-- The guest's dashboard; null when the key does not check out.
create or replace function public.get_profile(p_guest_id uuid, p_guest_key text)
returns jsonb
language plpgsql stable security definer set search_path = public
as $$
declare
  v_today date := public.today_wib();
  v_g public.guests%rowtype;
  v_daily jsonb;
  v_since date;
  v_days jsonb;
  v_recent jsonb;
  v_totals jsonb;
begin
  if p_guest_id is null or not public.guest_key_ok(p_guest_id, p_guest_key) then
    return null;
  end if;
  select * into v_g from guests g where g.id = p_guest_id;
  v_since := (v_g.created_at at time zone 'Asia/Jakarta')::date;

  -- Streak and the last seven days, by exactly the rule Hari ini uses.
  v_daily := public.get_daily(p_guest_id, p_guest_key);

  -- Package days since the guest first appeared (plus any older package they
  -- did), latest 60, each with the first attempt: the one the board counts.
  select jsonb_agg(jsonb_build_object(
      'date', d.daily_date, 'exam_id', d.id, 'title', d.title,
      'attempt_id', f.id, 'score', f.score, 'total', f.total,
      'on_time', f.id is not null and (f.submitted_at at time zone 'Asia/Jakarta')::date = d.daily_date
    ) order by d.daily_date)
  into v_days
  from (
    select e.id, e.title, e.daily_date
    from exams e
    where e.daily_date is not null and e.daily_date <= v_today
      and exists (select 1 from questions q where q.exam_id = e.id)
      and (
        e.daily_date >= v_since
        or exists (select 1 from attempts a where a.exam_id = e.id and a.guest_id = p_guest_id)
      )
    order by e.daily_date desc
    limit 60
  ) d
  left join lateral (
    select a.id, a.score, a.total, a.submitted_at
    from attempts a
    where a.exam_id = d.id and a.guest_id = p_guest_id
    order by a.submitted_at asc
    limit 1
  ) f on true;

  select jsonb_agg(to_jsonb(r) order by r.submitted_at desc)
  into v_recent
  from (
    select a.id as attempt_id, a.exam_id, e.title, e.daily_date, a.score, a.total, a.submitted_at
    from attempts a
    join exams e on e.id = a.exam_id
    where a.guest_id = p_guest_id
    order by a.submitted_at desc
    limit 20
  ) r;

  with firsts as (
    select distinct on (a.exam_id) a.score, a.total
    from attempts a
    where a.guest_id = p_guest_id
    order by a.exam_id, a.submitted_at asc
  )
  select jsonb_build_object(
    'attempts', (select count(*)::int from attempts a where a.guest_id = p_guest_id),
    'packages', (select count(*)::int from firsts),
    'average', (select round(avg(100.0 * f.score / nullif(f.total, 0)))::int from firsts f),
    'best', (select round(max(100.0 * f.score / nullif(f.total, 0)))::int from firsts f)
  )
  into v_totals;

  return jsonb_build_object(
    'today', v_today,
    'guest', jsonb_build_object(
      'id', v_g.id, 'nama', v_g.nama, 'username', v_g.username, 'joined', v_g.created_at
    ),
    'streak', v_daily -> 'streak',
    'week', coalesce(v_daily -> 'days', '[]'::jsonb),
    'totals', v_totals,
    'days', coalesce(v_days, '[]'::jsonb),
    'recent', coalesce(v_recent, '[]'::jsonb)
  );
end
$$;

